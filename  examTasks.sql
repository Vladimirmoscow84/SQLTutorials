/*
Задча 1
 * Написать один запрос, который возвращает:
 * - название библиотеки (name из libraries)
 * - город (city из libraries)
 * - имя менеджера (manager из libraries)
 * - жанр книги (genre из books)
 * - количество выдач (loans) в этом жанре в этой библиотеке
 * - общий срок выдачи книг (в днях) по этому жанру в этой библиотеке
 * Только те библиотеки + жанры, где:
 * - количество выдач > 1
 * - общий срок выдачи > среднего по всем библиотекам и жанрам
 * Отсортировать:
 * - по общему сроку выдачи по убыванию
 * - по названию библиотеки по возрастанию
 * - по жанру по возрастанию
 * Вывести ТОП-10
 */

WITH avg_date AS(
    SELECT AVG(DATEDIFF(return_date, loan_date)) AS avg_loans
    FROM loans
    WHERE return_date IS NOT NULL
),
 stats AS (
        SELECT lib.name,
            lib.city,
            lib.manager,
            b.genre,
            COUNT(*) AS count_loans,
            SUM(DATEDIFF(l.return_date, l.loan_date)) AS all_days
    FROM loans l
    JOIN libraries lib ON l.library_code = lib.code
    JOIN books b ON l.book_id = b.id
    WHERE l.return_date IS NOT NULL
    GROUP BY lib.name, lib.city, lib.manager, b.genre
    )

    SELECT name,
           city,
           manager,
           genre,
           count_loans,
           all_days
    FROM stats 
    CROSS JOIN avg_date
    WHERE count_loans>1 AND all_days>avg_loans
    ORDER BY all_days DESC, name ASC, genre ASC
    LIMIT 10;






-- Последний баланс клиента
-- 
-- Таблица: Transactions
-- +------------------+---------+
-- | Column Name      | Type    |
-- +------------------+---------+
-- | transaction_id   | int     |
-- | account_id       | int     |
-- | type             | varchar |
-- | amount           | int     |
-- | transaction_date | date    |
-- +------------------+---------+
-- 
-- - (transaction_id) — это первичный ключ.
-- - (account_id, transaction_date) — уникальная комбинация.
-- - Тип type может быть 'deposit' или 'withdraw'.
-- - Баланс каждого счёта начинается с 0.
-- 
-- Задание
-- 
-- Найдите баланс счёта для каждого account_id на дату 2022-12-31, учитывая все транзакции до этой даты.
-- Если по счёту не было транзакций до этой даты, баланс равен 0.
-- Верните account_id и balance.
-- Верните результат в любом порядке.
--
-- Пример
-- 
-- Ввод:
-- +----------------+------------+----------+--------+------------------+
-- | transaction_id | account_id | type     | amount | transaction_date |
-- +----------------+------------+----------+--------+------------------+
-- | 1              | 1          | deposit  | 2000   | 2022-11-01       |
-- | 2              | 1          | withdraw | 1000   | 2022-11-10       |
-- | 3              | 2          | deposit  | 3000   | 2022-12-01       |
-- | 4              | 2          | withdraw | 2000   | 2023-01-01       |
-- | 5              | 3          | deposit  | 1000   | 2023-01-01       |
-- +----------------+------------+----------+--------+------------------+
--
-- Вывод:
-- +------------+---------+
-- | account_id | balance |
-- +------------+---------+
-- | 1          | 1000    |
-- | 2          | 3000    |
-- | 3          | 0       |
-- +------------+---------+
--
-- Решение
    WITH accounts AS(
        SELECT DISTINCT account_id
        FROM transactions
    ),
     balances AS (
        SELECT account_id,
        SUM(
            CASE 
                WHEN type = 'deposit' THEN amount
                WHEN type = 'withdraw' THEN -amount
            END
        ) AS balance
        FROM transactions
        WHERE transaction_date <='2022-12-31'
        GROUP BY account_id
     )
     SELECT a.account_id,
            COALESCE (b.balance, 0)
    FROM accounts a
    LEFT JOIN balances b USING(account_id)
    ORDER BY 1 ASC;
